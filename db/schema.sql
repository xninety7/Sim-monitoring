CREATE INDEX IF NOT EXISTS devices_status_idx ON devices (status);
CREATE INDEX IF NOT EXISTS devices_name_idx ON devices (device_name);
CREATE INDEX IF NOT EXISTS devices_attached_pc_idx ON devices (attached_pc);

CREATE TABLE IF NOT EXISTS device_sims (
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    slot_number SMALLINT NOT NULL CHECK (slot_number IN (1, 2)),
    phone_number TEXT,
    telco_provider TEXT,
    PRIMARY KEY (device_id, slot_number)
);

ALTER TABLE device_sims ADD COLUMN IF NOT EXISTS phone_number TEXT;
ALTER TABLE device_sims ADD COLUMN IF NOT EXISTS telco_provider TEXT;

INSERT INTO device_sims (device_id, slot_number, phone_number)
SELECT id, 1, phone_number
FROM devices
WHERE phone_number IS NOT NULL
    AND NOT EXISTS (
            SELECT 1 FROM device_sims WHERE device_id = devices.id AND slot_number = 1
    )
ON CONFLICT (device_id, slot_number) DO NOTHING;

UPDATE device_sims AS slots
SET phone_number = devices.phone_number
FROM devices
WHERE slots.device_id = devices.id
    AND slots.slot_number = 1
    AND devices.phone_number IS NOT NULL
    AND slots.phone_number IS NULL;

INSERT INTO device_sims (device_id, slot_number, telco_provider)
SELECT id, 1, telco_provider
FROM devices
WHERE telco_provider IS NOT NULL
    AND NOT EXISTS (
            SELECT 1 FROM device_sims WHERE device_id = devices.id AND slot_number = 1
    )
ON CONFLICT (device_id, slot_number) DO NOTHING;

UPDATE device_sims AS slots
SET telco_provider = devices.telco_provider
FROM devices
WHERE slots.device_id = devices.id
    AND slots.slot_number = 1
    AND devices.telco_provider IS NOT NULL
    AND slots.telco_provider IS NULL;

UPDATE devices SET phone_number = NULL WHERE phone_number IS NOT NULL;
UPDATE devices SET telco_provider = NULL WHERE telco_provider IS NOT NULL;

CREATE TABLE IF NOT EXISTS activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS activity_log_created_at_idx ON activity_log (created_at DESC);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9._-]{1,50}$'),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ;
-- Set for people who sign in with Lark (see lib/lark.js).
ALTER TABLE users ADD COLUMN IF NOT EXISTS lark_open_id TEXT UNIQUE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS display_name TEXT;

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sessions_expires_at_idx ON sessions (expires_at);

-- Automatic SIM monitoring: each Mac runs an agent that reports the phones plugged into it.
CREATE TABLE IF NOT EXISTS agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
    token_hash TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_report_at TIMESTAMPTZ
);
ALTER TABLE agents ADD COLUMN IF NOT EXISTS report_interval_seconds INTEGER;

CREATE TABLE IF NOT EXISTS phones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform TEXT NOT NULL CHECK (platform IN ('android', 'ios')),
    hardware_id TEXT NOT NULL,
    model TEXT,
    os_version TEXT,
    agent_id BIGINT REFERENCES agents(id) ON DELETE SET NULL,
    device_id BIGINT UNIQUE REFERENCES devices(id) ON DELETE SET NULL,
    connected BOOLEAN NOT NULL DEFAULT false,
    problem TEXT,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ,
    UNIQUE (platform, hardware_id)
);

-- baseline_sim_key is the SIM the slot is expected to hold; a different current SIM means it was swapped.
CREATE TABLE IF NOT EXISTS phone_slots (
    phone_id BIGINT NOT NULL REFERENCES phones(id) ON DELETE CASCADE,
    slot_number SMALLINT NOT NULL CHECK (slot_number BETWEEN 1 AND 4),
    state TEXT NOT NULL CHECK (state IN ('present', 'removed', 'changed', 'empty')),
    sim_key TEXT,
    sim_label TEXT,
    carrier TEXT,
    phone_number TEXT,
    baseline_sim_key TEXT,
    baseline_sim_label TEXT,
    baseline_carrier TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (phone_id, slot_number)
);
