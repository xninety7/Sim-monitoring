CREATE INDEX IF NOT EXISTS devices_status_idx ON devices (status);
CREATE INDEX IF NOT EXISTS devices_name_idx ON devices (device_name);
CREATE INDEX IF NOT EXISTS devices_attached_pc_idx ON devices (attached_pc);

CREATE TABLE IF NOT EXISTS device_sims (
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    slot_number SMALLINT NOT NULL CHECK (slot_number IN (1, 2)),
    sim_number TEXT,
    iccid TEXT,
    imei TEXT,
    PRIMARY KEY (device_id, slot_number)
);

CREATE UNIQUE INDEX IF NOT EXISTS device_sims_sim_number_uidx ON device_sims (sim_number) WHERE sim_number IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS device_sims_iccid_uidx ON device_sims (iccid) WHERE iccid IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS device_sims_imei_uidx ON device_sims (imei) WHERE imei IS NOT NULL;

INSERT INTO device_sims (device_id, slot_number, sim_number, iccid, imei)
SELECT id, 1, sim_number, iccid, imei
FROM devices
WHERE sim_number IS NOT NULL OR iccid IS NOT NULL OR imei IS NOT NULL
ON CONFLICT (device_id, slot_number) DO NOTHING;

CREATE TABLE IF NOT EXISTS activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS activity_log_created_at_idx ON activity_log (created_at DESC);
