CREATE TABLE IF NOT EXISTS devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_name TEXT NOT NULL CHECK (length(trim(device_name)) > 0),
    attached_pc TEXT NOT NULL CHECK (length(trim(attached_pc)) > 0),
    phone_number TEXT NOT NULL CHECK (length(trim(phone_number)) > 0),
    anydesk_id TEXT,
    color TEXT,
    telco_provider TEXT,
    sim_slot_count SMALLINT NOT NULL DEFAULT 1 CHECK (sim_slot_count IN (1, 2)),
    status TEXT NOT NULL DEFAULT 'inactive' CHECK (status IN ('active', 'inactive', 'offline', 'suspended')),
    last_seen TEXT NOT NULL DEFAULT '',
    sim_number TEXT UNIQUE,
    iccid TEXT UNIQUE,
    imei TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE devices ADD COLUMN IF NOT EXISTS anydesk_id TEXT;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS color TEXT;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS telco_provider TEXT;
ALTER TABLE devices ADD COLUMN IF NOT EXISTS sim_slot_count SMALLINT NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'devices_sim_slot_count_check'
          AND conrelid = 'devices'::regclass
    ) THEN
        ALTER TABLE devices
            ADD CONSTRAINT devices_sim_slot_count_check CHECK (sim_slot_count IN (1, 2));
    END IF;
