CREATE INDEX IF NOT EXISTS devices_status_idx ON devices (status);
CREATE INDEX IF NOT EXISTS devices_name_idx ON devices (device_name);
CREATE INDEX IF NOT EXISTS devices_attached_pc_idx ON devices (attached_pc);

CREATE TABLE IF NOT EXISTS device_sims (
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    slot_number SMALLINT NOT NULL CHECK (slot_number IN (1, 2)),
    phone_number TEXT,
    PRIMARY KEY (device_id, slot_number)
);

ALTER TABLE device_sims ADD COLUMN IF NOT EXISTS phone_number TEXT;

INSERT INTO device_sims (device_id, slot_number, phone_number)
SELECT id, 1, phone_number
FROM devices
WHERE phone_number IS NOT NULL
    AND NOT EXISTS (
            SELECT 1 FROM device_sims WHERE device_id = devices.id AND slot_number = 1
    )
ON CONFLICT (device_id, slot_number) DO NOTHING;

UPDATE device_sims AS slots
SET phone_number = devices.phone_number
FROM devices
WHERE slots.device_id = devices.id
    AND slots.slot_number = 1
    AND devices.phone_number IS NOT NULL
    AND slots.phone_number IS NULL;

UPDATE devices SET phone_number = NULL WHERE phone_number IS NOT NULL;

CREATE TABLE IF NOT EXISTS activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    details TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS activity_log_created_at_idx ON activity_log (created_at DESC);
